export interface IconProps {
  name: string;
  size?: number;
  color?: string;
  strokeWidth?: number;
  accessibilityLabel?: string;
}

export function VectorIcon({
  name,
  size = 20,
  color = '#0f172a',
  strokeWidth = 2,
  accessibilityLabel,
}: IconProps) {
  const resolvedName = ICON_MAP[name] ? name : ALIASES[name.toLowerCase()] ?? name;
  const IconComponent = ICON_MAP[resolvedName] ?? Package;

  return (
    <IconComponent
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      accessibilityLabel={accessibilityLabel || `${resolvedName} icon`}
    />
  );
}
